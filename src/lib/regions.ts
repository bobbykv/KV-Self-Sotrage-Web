const CA_CODES = new Set(CA_PROVINCES.map((p) => p.code));
const US_CODES = new Set(US_STATES.map((p) => p.code));

export function isRegionCode(value: string): boolean {
  const code = value.trim().toUpperCase();
  return CA_CODES.has(code) || US_CODES.has(code);
}

/** Dropdown value plus free text when the saved region is not a known code. */
export function splitStoredRegion(value?: string | null): { code: string; other: string } {
  const v = (value ?? "").trim();
  if (!v) return { code: "NS", other: "" };
  if (isRegionCode(v)) return { code: v.toUpperCase(), other: "" };
  return { code: "OTHER", other: v };
}

export function countryForRegion(region: string): { country: string; countryCode: string } {
  const code = region.trim().toUpperCase();
  if (CA_CODES.has(code)) return { country: "Canada", countryCode: "CA" };
  if (US_CODES.has(code)) return { country: "United States", countryCode: "US" };
  return { country: "", countryCode: "" };
}
